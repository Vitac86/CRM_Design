(function (global) {
  'use strict';

  var ns = global.CRMDocumentBuilder = global.CRMDocumentBuilder || {};
  var IO = {};

  function ordered(value) {
    if (Array.isArray(value)) return value.map(ordered);
    if (!value || typeof value !== 'object') return value;
    var result = {};
    Object.keys(value).sort().forEach(function (key) { result[key] = ordered(value[key]); });
    return result;
  }

  function stableStringify(value) {
    return JSON.stringify(ordered(value), null, 2) + '\n';
  }

  function safeFilename(name) {
    return String(name || 'document').replace(/[^A-Za-z0-9._-]+/g, '-').replace(/^-+|-+$/g, '') || 'document';
  }

  function download(filename, content, type) {
    var blob = content instanceof Blob ? content : new Blob([content], { type: type || 'application/octet-stream' });
    var url = URL.createObjectURL(blob);
    var anchor = document.createElement('a');
    anchor.href = url;
    anchor.download = safeFilename(filename);
    document.body.appendChild(anchor);
    anchor.click();
    anchor.remove();
    global.setTimeout(function () { URL.revokeObjectURL(url); }, 0);
    return blob;
  }

  function productionJs(project) {
    var template = ns.schema.toProduction(project);
    var json = stableStringify(template).trimEnd();
    return "// Generated by the browser-only CRM document template builder.\n" +
      "// Declarative field map: no executable formatters or conditions.\n\n" +
      "(function (global) {\n" +
      "  'use strict';\n\n" +
      "  var TEMPLATE = " + json.split('\n').join('\n  ') + ";\n\n" +
      "  global.CRMDocumentEngine = global.CRMDocumentEngine || {};\n" +
      "  global.CRMDocumentEngine.fieldMaps = global.CRMDocumentEngine.fieldMaps || {};\n" +
      "  global.CRMDocumentEngine.fieldMaps[TEMPLATE.id] = TEMPLATE;\n\n" +
      "}(typeof window !== 'undefined' ? window : this));\n";
  }

  function registryFragment(project) {
    return {
      id: project.templateId,
      title: project.title,
      description: project.description || '',
      category: project.category || '',
      appliesTo: ns.schema.clone(project.appliesTo || []),
      overlayTemplateId: project.templateId,
      pdfOutputFilename: project.outputFilename,
      fields: ns.schema.clone((project.wizard || {}).fields || []),
      checkFields: ns.schema.clone((project.wizard || {}).checkFields || []),
      companyFields: ns.schema.clone((project.wizard || {}).companyFields || [])
    };
  }

  function qaReport(project, validation, batch) {
    return {
      schemaVersion: 1,
      templateId: project.templateId,
      sourcePdfSha256: project.sourcePdfSha256 || '',
      qaStatus: ns.schema.clone(project.qa || {}),
      validation: validation || { errors: [], warnings: [] },
      batch: batch || null
    };
  }

  function importProjectText(text) {
    var parsed;
    try { parsed = JSON.parse(text); }
    catch (error) { throw new Error('JSON проекта повреждён: ' + error.message); }
    var migrated = ns.schema.migrate(parsed);
    if (migrated.errors.length) {
      var first = migrated.errors[0];
      throw new Error(first.path + ': ' + first.message);
    }
    return migrated;
  }

  function semantic(value) { return JSON.stringify(ordered(value)); }

  IO.ordered = ordered;
  IO.stableStringify = stableStringify;
  IO.safeFilename = safeFilename;
  IO.download = download;
  IO.productionJs = productionJs;
  IO.registryFragment = registryFragment;
  IO.qaReport = qaReport;
  IO.importProjectText = importProjectText;
  IO.semanticEqual = function (a, b) { return semantic(a) === semantic(b); };
  IO.exportProject = function (project) { return stableStringify(project); };
  IO.exportFixtures = function (project) { return stableStringify(ns.fixtures.exportData(project)); };
  IO.exportRegistry = function (project) { return stableStringify(registryFragment(project)); };
  IO.exportQa = function (project, validation, batch) { return stableStringify(qaReport(project, validation, batch)); };
  ns.io = IO;
}(typeof window !== 'undefined' ? window : this));
